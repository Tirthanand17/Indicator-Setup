import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {validateCalendar, calendarMaintenanceStatus} from '../edge-cloudflare/calendar-schema.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const manifest = path.join(root, 'cloud-alerts/cloud_alerts/data/nse-fo-calendar.json');
const generated = path.join(root, 'edge-cloudflare/calendar-data.mjs');
const seal = path.join(root, 'cloud-alerts/cloud_alerts/calendar_digest.py');
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
export function calendarArtifacts(bytes) {
  if (bytes.length > 100_000) throw new Error('CALENDAR_TOO_LARGE');
  const calendar = validateCalendar(JSON.parse(bytes.toString('utf8')));
  return {calendar,
    javascript: '// Generated by scripts/calendar-maintenance.mjs; edit the canonical JSON.\n' +
      'const freeze = (v) => { if (v && typeof v === "object") { Object.values(v).forEach(freeze); Object.freeze(v); } return v; };\n' +
      `export const NSE_FO_CALENDAR = freeze(${JSON.stringify(calendar, null, 2)});\n`,
    python: '# Generated by scripts/calendar-maintenance.mjs; seals the reviewed JSON bytes.\n' +
      `CALENDAR_SHA256 = '${hash(bytes)}'\n`};
}

/** No network, deployment, active configuration or scheduler writes. */
export function runCalendarMaintenance(args, log = console.log) {
  try {
    if (args.length === 1 && ['--check', '--write'].includes(args[0])) {
      const artifacts = calendarArtifacts(readFileSync(manifest));
      for (const [target, expected] of [[generated, artifacts.javascript], [seal, artifacts.python]]) {
        if (args[0] === '--write') writeFileSync(target, expected);
        else if (readFileSync(target, 'utf8') !== expected) throw new Error('CALENDAR_GENERATED_DATA_DRIFT');
      }
      log('Calendar generated data matches the reviewed manifest.'); return 0;
    }
    if (args.length === 2 && args[0] === 'status') {
      log(JSON.stringify(calendarMaintenanceStatus(calendarArtifacts(readFileSync(manifest)).calendar, args[1]))); return 0;
    }
    if (args.length === 4 && args[0] === 'prepare') {
      const bytes = readFileSync(args[1]);
      const artifacts = calendarArtifacts(bytes);
      const current = calendarArtifacts(readFileSync(manifest)).calendar;
      if (artifacts.calendar.revision === current.revision) throw new Error('NEW_CALENDAR_REVISION_REQUIRED');
      if (artifacts.calendar.reviewedAt > new Date().toISOString().slice(0, 10)) throw new Error('FUTURE_REVIEW_DATE');
      for (const source of artifacts.calendar.sources) {
        const pdf = readFileSync(path.join(args[2], `FAOP${source.id.split('/')[2]}.pdf`));
        if (pdf.length > 10_000_000 || !pdf.subarray(0, 5).equals(Buffer.from('%PDF-')) || hash(pdf) !== source.sha256)
          throw new Error('SOURCE_PDF_HASH_MISMATCH');
      }
      // mkdir fails if the destination exists. Never overwrite or promote active files.
      mkdirSync(args[3]);
      for (const [name, content] of [['nse-fo-calendar.json', bytes], ['calendar-data.mjs', artifacts.javascript],
        ['calendar_digest.py', artifacts.python], ['REVIEW.txt',
          'STAGED ONLY. PDF hashes checked locally; authenticity and dates still require human review of official NSE F&O circulars.\n' +
          'Review manifest diff, annual coverage, amendments and special sessions. Run full quality checks before promoting all three files together.\n' +
          'New revisions require halted-state/archive compatibility review; do not rewrite persisted calendar versions or resume automatically.\n']])
        writeFileSync(path.join(args[3], name), content, {flag: 'wx'});
      log('Staged review bundle created. No active calendar changed; source authenticity is not certified.'); return 0;
    }
    log('Usage: calendar-maintenance.mjs --check | --write | status YYYY-MM-DD | prepare candidate.json pdf-directory NEW-output-directory');
    return 2;
  } catch (error) {
    const code = error instanceof Error && /^[A-Z_]+$/.test(error.message) ? error.message : 'CALENDAR_MAINTENANCE_FAILED';
    log(code); return 1;
  }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exitCode = runCalendarMaintenance(process.argv.slice(2));
